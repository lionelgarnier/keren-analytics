// Canonical fields whose custom-dimension naming Keren auto-detects. Derived
// straight from the alias table + mapping expressions: an agent that names a
// custom dimension one of `recognizedNames` skips manual mapping in the wizard.
function buildNamingConventions() {
  return Object.keys(ALIASES).map((field) => {
    const exprs = mappingExpressions[field] || {};
    const builtinExpressions = Object.entries(exprs)
      .filter(([variant]) => variant !== "custom")
      .map(([, expr]) => expr);
    const customDimensionExpression = exprs.custom || null;
    return {
      canonicalField: field,
      builtinExpressions,
      customDimensionExpression,
      recommendedCustomDimensionName: ALIASES[field].exact[0],
      recognizedNames: ALIASES[field].exact.slice(),
      recognizedNamePattern: ALIASES[field].pattern.source,
      note:
        "If you emit this as a custom dimension, name it one of recognizedNames " +
        "(or match recognizedNamePattern) so Keren auto-maps it with no manual setup.",
    };
  });
}

function buildSignals() {
  return Object.entries(SIGNAL_WEIGHTS)
    .filter(([key]) => key !== "userIdDegraded")
    .map(([key, weight]) => ({
      id: key,
      label: weight.label,
      points: weight.points,
      category: weight.category,
      description: weight.description,
      ...(SIGNAL_DETAIL[key] || {}),
    }))
    .sort((a, b) => b.points - a.points);
}

function buildRecipes() {
  const stack = STACK_HINTS.generic;
  // Iterate the SCORED signals (minus the userIdDegraded variant), not
  // PROMPT_TEMPLATES' own keys — otherwise the recipe set silently drifts from
  // the signal set: dependencies/exceptions (10 pts each) had no recipe while
  // userIdDegraded (not a signal) had one. Every scored signal must have a
  // template; the anti-drift test enforces it.
  return Object.keys(SIGNAL_WEIGHTS)
    .filter((signal) => signal !== "userIdDegraded")
    .map((signal) => {
      const template = PROMPT_TEMPLATES[signal];
      if (!template) {
        throw new Error(`No PROMPT_TEMPLATES entry for scored signal "${signal}"`);
      }
      return { signal, label: signalLabel(signal), prompt: template(stack, null) };
    });
}

/**
 * Build the public telemetry contract. Deterministic except for
 * `generatedAt`: `contractVersion` is a content hash that excludes the
 * timestamp, so it only changes when the underlying signals/mapping/prompts
 * change — agents can cache against it.
 *
 * @returns {object} the contract
 */
export function buildTelemetryContract() {
  const maxScore = Object.entries(SIGNAL_WEIGHTS).reduce(
    (sum, [key, w]) => (key === "userIdDegraded" ? sum : sum + w.points),
    0
  );

  const body = {
    product: PRODUCT,
    privacy: {
      rawLogsLeaveTenant: false,
      summary:
        "Keren stores only aggregates — no raw log rows, no PII. Telemetry you " +
        "emit is queried in place via KQL; pseudonymize user ids and never send PII.",
    },
    scoring: {
      maxScore,
      grades: GRADE_THRESHOLDS,
      note:
        "Score = sum of points for signals present. Aim for grade A (>=90%). " +
        "Points and grades mirror the live readiness scorer.",
    },
    signals: buildSignals(),
    namingConventions: buildNamingConventions(),
    instrumentationConfig: INSTRUMENTATION_CONFIG,
    stacks: Object.entries(STACK_HINTS).map(([key, hint]) => ({
      key,
      name: hint.name,
      recommendedSdk: hint.sdk,
    })),
    recipes: buildRecipes(),
  };

  const contractVersion = crypto
    .createHash("sha256")
    .update(JSON.stringify(body))
    .digest("hex")
    .slice(0, 12);

  return {
    $schema: `${PRODUCT.url}/.well-known/telemetry-contract.json`,
    contractVersion,
    generatedAt: new Date().toISOString(),
    ...body,
  };
}

/**
 * Render the contract as an llms.txt-style Markdown brief — the human/LLM
 * readable companion to the JSON, discoverable at /llms.txt.
 *
 * @param {object} [contract] - defaults to a freshly built contract
 * @returns {string} Markdown
 */
export function renderContractMarkdown(contract = buildTelemetryContract()) {
  const lines = [];
  lines.push(`# ${contract.product.name} — Telemetry Contract`);
  lines.push("");
  lines.push(`> ${contract.product.description}`);
  lines.push("");
  lines.push(
    `Contract version: \`${contract.contractVersion}\` · ` +
      `Machine-readable: ${contract.product.url}/.well-known/telemetry-contract.json`
  );
  lines.push("");
  lines.push(
    "Instrument your app's Azure Application Insights so these signals are " +
      "present, name custom dimensions as below, and Keren renders the full " +
      "dashboard with no manual mapping.");
  lines.push("");

  lines.push("## Privacy");
  lines.push("");
  lines.push(`- ${contract.privacy.summary}`);
  lines.push("");

  lines.push("## Signals (readiness points)");
  lines.push("");
  lines.push(`Score out of ${contract.scoring.maxScore}. Aim for grade A (>=90%).`);
  lines.push("");
  for (const s of contract.signals) {
    const target =
      s.appInsightsTable
        ? `\`${s.appInsightsTable}\` table`
        : s.appInsightsField
          ? `\`${s.appInsightsField}\``
          : s.appInsightsFields
            ? s.appInsightsFields.map((f) => `\`${f}\``).join(", ")
            : "";
    lines.push(`### ${s.label} — ${s.points} pts (${s.category})`);
    lines.push("");
    lines.push(`- Lands in: ${target}`);
    lines.push(`- How: ${s.howToEmit}`);
    if (s.verifyKql) lines.push(`- Verify (KQL): \`${s.verifyKql}\``);
    lines.push("");
  }

  lines.push("## Custom dimension naming");
  lines.push("");
  lines.push(
    "Built-in fields are detected automatically. If you must use a custom " +
      "dimension, use a recognized name so it auto-maps:");
  lines.push("");
  for (const n of contract.namingConventions) {
    lines.push(
      `- **${n.canonicalField}** → recommended \`${n.recommendedCustomDimensionName}\` ` +
        `(also: ${n.recognizedNames.slice(0, 6).join(", ")}…)`
    );
  }
  lines.push("");

  lines.push("## Config best practices");
  lines.push("");
  for (const c of contract.instrumentationConfig) {
    lines.push(`- **${c.title}** — ${c.detail}`);
  }
  lines.push("");

  lines.push("## SDK per stack");
  lines.push("");
  for (const st of contract.stacks) {
    lines.push(`- ${st.name}: \`${st.recommendedSdk}\``);
  }
  lines.push("");

  lines.push("## Ready-to-paste prompts");
  lines.push("");
  lines.push(
    "One prompt per signal — paste into Cursor / Copilot / Claude Code to " +
      "close a gap. Full text in the JSON contract under `recipes`.");
  lines.push("");
  for (const r of contract.recipes) {
    lines.push(`- ${r.label} (\`${r.signal}\`)`);
  }
  lines.push("");

  return lines.join("\n");
}
