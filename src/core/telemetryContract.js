/**
 * Public telemetry contract (ADR 0006, Phase 0).
 *
 * The "what to emit so Keren lights up green from day one" spec, served to
 * coding agents (Cursor / Copilot / Claude Code) at a stable URL so they can
 * instrument an app's Application Insights telemetry *before* it ever reaches
 * the setup wizard.
 *
 * Single source of truth: every value here is DERIVED from the modules that
 * already drive the product — the readiness scorer (`readinessScore.js`), the
 * canonical mapping (`mapping.js`), and the in-app remediation prompts
 * (`promptGenerator.js`). Nothing about "what Keren wants" is re-stated by
 * hand, so the published contract can never drift from runtime behaviour.
 * `tests/telemetryContract.test.js` pins that invariant; the committed
 * snapshots under `public/` are regenerated by `npm run build:contract`.
 */

